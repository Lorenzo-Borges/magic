    private void atualizarLista() {
        try {
            br.com.proway.magic.dao.CartasDAO dao = new br.com.proway.magic.dao.CartasDAO();
            java.util.ArrayList<br.com.proway.magic.modelo.Carta> lista = dao.consultarTodos();
            
            // Cria um modelo para o seu jList1
            javax.swing.DefaultListModel<String> modelo = new javax.swing.DefaultListModel<>();
            for(br.com.proway.magic.modelo.Carta c : lista) {
                // Exibe o ID e o Nome na lista
                modelo.addElement(c.getId() + " - " + c.getNome() + " (" + c.getCor() + ")");
            }
            jList1.setModel(modelo);
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao carregar lista: " + e.getMessage());
        }
    }

