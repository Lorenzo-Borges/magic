    private void jButtonSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSalvarActionPerformed
                                             
        try {
            // Usa o caminho completo para não confundir com a tela que também chama Carta
            br.com.proway.magic.modelo.Carta carta = new br.com.proway.magic.modelo.Carta();
            
            carta.setNome(jTextFieldNome.getText());
            carta.setTipo(jTextFieldTipo.getText());
            carta.setCor(jComboBox1.getSelectedItem().toString());
            
            // Converte os textos para os formatos corretos
            carta.setPreco(Double.parseDouble(jTextFieldPreco.getText()));
            
            // Atenção: usando os nomes de campos gerados pelo seu design visual
            carta.setAtaque(Integer.parseInt(jTextFieldCor1.getText())); // Este é o campo de Ataque
            carta.setResistencia(Integer.parseInt(jTextFieldPreco1.getText())); // Este é o campo de Resistência

            // Salva no banco de dados
            br.com.proway.magic.dao.CartasDAO dao = new br.com.proway.magic.dao.CartasDAO();
            dao.inserir(carta);

            javax.swing.JOptionPane.showMessageDialog(this, "Carta salva com sucesso!");
            
            // Limpa a tela e atualiza a lista de cartas
            jButtonCancelarActionPerformed(null); 
            atualizarLista();

        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Verifique os campos! Preço, Ataque e Resistência devem ser numéricos.");
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao salvar a carta no banco: " + ex.getMessage());
        }       
    }//GEN-LAST:event_jButtonSalvarActionPerformed

